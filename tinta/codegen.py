"""Generate typed Tinta color methods from a colors.ini file."""

from __future__ import annotations

import argparse
import configparser
import sys
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Sequence, Tuple, Union

# Names that must not be used as color methods (would clobber Tinta APIs).
RESERVED_COLOR_NAMES = frozenset(
    {
        "bold",
        "b",
        "underline",
        "u",
        "_",
        "strikethrough",
        "dim",
        "normal",
        "default",
        "clear",
        "nl",
        "print",
        "tint",
        "inspect",
        "push",
        "pop",
        "to_str",
        "discover",
        "clearline",
        "up",
        "color",
        "color_code",
        "style",
        "parts",
        "parts_fmt",
        "parts_pln",
        "parts_esc",
        "current_part",
        "has_formatting",
        "set_color",
        "load_colors",
        "styler",
        "part",
        "get",
    }
)


def _file_header(
    source: str,
    docstring: str,
    *,
    typing_imports: str = "Any",
    extra_imports: str = "",
) -> str:
    header = (
        "#!/usr/bin/env python\n"
        "\n"
        "# Tinta — Copyright (c) 2026 github.com/brandonscript\n"
        "# Licensed under the MIT License. See LICENSE.\n"
        "\n"
        "# AUTO-GENERATED by `python -m tinta codegen` — do not edit.\n"
        f"# Source: {source}\n"
        "\n"
        f'"""{docstring}"""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        f"from typing import {typing_imports}\n"
    )
    if extra_imports:
        header += extra_imports
    return header


def parse_colors_ini(path: Union[str, Path]) -> Dict[str, int]:
    """Parse a colors.ini file into a name -> ANSI code mapping.

    Keys are lowercased (ConfigParser default). Gray/grey aliases are added
    to match runtime AnsiColors behavior.
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(f"colors.ini not found: {path}")

    parser = configparser.ConfigParser()
    parser.read(path)
    if "colors" not in parser:
        raise ValueError(f"No [colors] section in {path}")

    colors = {k: int(v) for (k, v) in parser["colors"].items()}
    return _with_gray_aliases(colors)


def _with_gray_aliases(colors: Mapping[str, int]) -> Dict[str, int]:
    """Add gray/grey alias keys the same way AnsiColors does at runtime."""
    result = dict(colors)
    for search, repl in (("gray", "grey"), ("grey", "gray")):
        for key, code in list(result.items()):
            if search in key:
                alias = key.replace(search, repl)
                if alias not in result:
                    result[alias] = code
    return result


def filter_color_names(
    colors: Mapping[str, int],
    *,
    reserved: frozenset[str] = RESERVED_COLOR_NAMES,
) -> Tuple[List[str], List[str]]:
    """Split color names into usable methods vs reserved conflicts.

    Returns:
        (valid_names, reserved_names) — both sorted.
    """
    valid: List[str] = []
    conflicts: List[str] = []
    for name in colors:
        if name.startswith("_") or name in reserved:
            conflicts.append(name)
        else:
            valid.append(name)
    return sorted(valid), sorted(conflicts)


def _method_source(name: str, indent: str = "    ") -> str:
    return (
        f"{indent}def {name}(self, *s: Any, sep: str = \" \") -> Tinta:\n"
        f'{indent}    """Colorize segments with \'{name}\'."""\n'
        f'{indent}    return cast("Tinta", self.tint(*s, color="{name}", sep=sep))\n'
    )


def generate_subclass_source(
    colors: Mapping[str, int],
    *,
    source: str = "colors.ini",
    base_import: str = "from tinta import Tinta as _Tinta",
    class_name: str = "Tinta",
    base_name: str = "_Tinta",
) -> str:
    """Generate a typed Tinta subclass module with one method per color."""
    valid, conflicts = filter_color_names(colors)
    if conflicts:
        conflict_list = ", ".join(conflicts)
        raise ValueError(
            f"Cannot generate color methods that clobber Tinta APIs: {conflict_list}. "
            f"Rename these colors in your colors.ini."
        )

    docstring = "Typed Tinta subclass with color methods from colors.ini."
    parts = [
        _file_header(source, docstring, typing_imports="Any, cast"),
        base_import,
        "",
        "",
        f"class {class_name}({base_name}):",
    ]
    if not valid:
        parts.append("    pass")
    else:
        for i, name in enumerate(valid):
            if i:
                parts.append("")
            parts.append(_method_source(name).rstrip())
    parts.append("")
    return "\n".join(parts) + "\n"


def generate_mixin_source(
    colors: Mapping[str, int],
    *,
    source: str = "tinta/colors.ini",
) -> str:
    """Generate the first-party _ColorMethods mixin from the bundled colors.ini."""
    valid, conflicts = filter_color_names(colors)
    if conflicts:
        conflict_list = ", ".join(conflicts)
        raise ValueError(
            f"Bundled colors.ini has reserved names: {conflict_list}."
        )

    docstring = "Color methods for the default tinta/colors.ini (generated)."
    # Forward-ref Tinta; mixin is combined with Tinta at class definition time.
    parts = [
        _file_header(
            source,
            docstring,
            typing_imports="Any, TYPE_CHECKING",
            extra_imports=(
                "\n"
                "if TYPE_CHECKING:\n"
                "    from .tinta import Tinta\n"
            ),
        ),
        "",
        "class _ColorMethods:",
        '    """Mixin providing typed color builder methods for default colors."""',
        "",
        "    if TYPE_CHECKING:",
        "",
        "        def tint(self, *args: Any, **kwargs: Any) -> Tinta: ...",
        "",
    ]
    if not valid:
        parts.append("    pass")
    else:
        for i, name in enumerate(valid):
            if i:
                parts.append("")
            method = (
                f"    def {name}(self, *s: Any, sep: str = \" \") -> Tinta:\n"
                f'        """Colorize segments with \'{name}\'."""\n'
                f'        return self.tint(*s, color="{name}", sep=sep)\n'
            )
            parts.append(method.rstrip())
    parts.append("")
    return "\n".join(parts) + "\n"


def write_typings(
    ini_path: Union[str, Path],
    out_path: Union[str, Path],
    *,
    mixin: bool = False,
) -> Path:
    """Read colors.ini and write a generated typings module."""
    ini_path = Path(ini_path)
    out_path = Path(out_path)
    colors = parse_colors_ini(ini_path)
    source = str(ini_path)
    if mixin:
        content = generate_mixin_source(colors, source=source)
    else:
        content = generate_subclass_source(colors, source=source)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(content, encoding="utf-8")
    return out_path


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m tinta codegen",
        description="Generate typed Tinta color methods from a colors.ini file.",
    )
    parser.add_argument(
        "ini",
        type=Path,
        help="Path to colors.ini",
    )
    parser.add_argument(
        "-o",
        "--out",
        type=Path,
        required=True,
        help="Output .py path for the generated module",
    )
    parser.add_argument(
        "--mixin",
        action="store_true",
        help="Generate the internal _ColorMethods mixin instead of a Tinta subclass",
    )
    args = parser.parse_args(argv)

    try:
        out = write_typings(args.ini, args.out, mixin=args.mixin)
    except (FileNotFoundError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
